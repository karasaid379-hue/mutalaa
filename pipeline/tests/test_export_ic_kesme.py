"""`mutalaa export ic-kesme` testleri (A05.2, K-36 madde 3).

Gercek liste testleri depodaki `shared/data/ic-kesme.txt` dosyasini yalniz okur. Uretim ve
hata testleri `tmp_path` altinda sentetik listeler kullanir. Kaynak yalniz ASCII'dir.
"""

import hashlib
import re
from pathlib import Path

import pytest
from typer.testing import CliRunner, Result

from mutalaa_pipeline.cli import app
from mutalaa_pipeline.export import ic_kesme
from mutalaa_pipeline.export.ortak import GirdiHatasi, depo_koku

runner = CliRunner()

BASLANGIC_LISTESI = ("i'caz", "kur'an", "lem'a", "ma'na", "mu'min", "san'at", "te'sir")
URETILEN_YOLLAR = (ic_kesme.TS_YOLU, ic_kesme.CS_YOLU)


def liste_yaz(kok: Path, icerik: bytes) -> None:
    yol = kok / ic_kesme.TXT_YOLU
    yol.parent.mkdir(parents=True, exist_ok=True)
    yol.write_bytes(icerik)


def liste_kur(kok: Path, girdiler: tuple[str, ...] = ("a'b", "c'de", "fg'h'i")) -> bytes:
    veri = "".join(f"{girdi}\n" for girdi in girdiler).encode("utf-8")
    liste_yaz(kok, veri)
    return veri


def calistir(kok: Path, *ek: str) -> Result:
    return runner.invoke(app, ["export", "ic-kesme", "--kok", str(kok), *ek])


def uretilenler(kok: Path) -> dict[str, bytes]:
    return {yol: (kok / yol).read_bytes() for yol in URETILEN_YOLLAR}


# --- Gercek depo -------------------------------------------------------------------------


def test_gercek_liste_baslangic_girdileri_ve_bicim() -> None:
    yol = depo_koku() / ic_kesme.TXT_YOLU
    veri = yol.read_bytes()
    assert not veri.startswith(b"\xef\xbb\xbf")
    assert b"\r" not in veri
    assert veri.endswith(b"\n")
    liste = ic_kesme.oku(depo_koku())
    assert liste.girdiler == BASLANGIC_LISTESI
    assert list(liste.girdiler) == sorted(liste.girdiler)
    assert liste.sha256 == hashlib.sha256(veri).hexdigest()


def test_gercek_depoda_check_sifir() -> None:
    sonuc = runner.invoke(app, ["export", "ic-kesme", "--check"])
    assert sonuc.exit_code == 0, sonuc.output
    assert "fark yok" in sonuc.output


# --- Uretim ------------------------------------------------------------------------------


def test_uretim_iki_dosya_yazar_ve_check_gecer(tmp_path: Path) -> None:
    veri = liste_kur(tmp_path)
    sonuc = calistir(tmp_path)
    assert sonuc.exit_code == 0, sonuc.output
    for yol in URETILEN_YOLLAR:
        assert f"yazildi: {yol}" in sonuc.output
        icerik = (tmp_path / yol).read_bytes()
        assert not icerik.startswith(b"\xef\xbb\xbf")
        assert b"\r" not in icerik
        assert icerik.endswith(b"\n")
    assert calistir(tmp_path, "--check").exit_code == 0
    assert (tmp_path / ic_kesme.TXT_YOLU).read_bytes() == veri  # girdi dosyasina dokunulmaz


def test_ts_ve_cs_icerigi(tmp_path: Path) -> None:
    veri = liste_kur(tmp_path)
    assert calistir(tmp_path).exit_code == 0
    ozet = hashlib.sha256(veri).hexdigest()
    ts = (tmp_path / ic_kesme.TS_YOLU).read_text(encoding="utf-8")
    cs = (tmp_path / ic_kesme.CS_YOLU).read_text(encoding="utf-8")
    assert ts == "\n".join(
        [
            f"// {ic_kesme.UYARI}",
            "// Kaynak: shared/data/ic-kesme.txt",
            f"// SHA-256: {ozet}",
            "",
            f"/** {ic_kesme.ACIKLAMA} */",
            "export const IC_KESME: readonly string[] = Object.freeze([",
            '  "a\'b",',
            '  "c\'de",',
            "  \"fg'h'i\",",
            "]);",
            "",
        ]
    )
    assert cs == "\n".join(
        [
            "// <auto-generated/>",
            f"// {ic_kesme.UYARI}",
            "// Kaynak: shared/data/ic-kesme.txt",
            f"// SHA-256: {ozet}",
            "",
            "namespace Mutalaa.Domain.Text;",
            "",
            "/// <summary>",
            f"/// {ic_kesme.ACIKLAMA}",
            "/// </summary>",
            "internal static class IcKesme",
            "{",
            "    internal static IReadOnlyList<string> Entries { get; } =",
            "    [",
            '        "a\'b",',
            '        "c\'de",',
            "        \"fg'h'i\",",
            "    ];",
            "}",
            "",
        ]
    )


def test_gercek_kopyalar_listedeki_girdileri_sirayla_icerir() -> None:
    kok = depo_koku()
    ts = (kok / ic_kesme.TS_YOLU).read_text(encoding="utf-8")
    cs = (kok / ic_kesme.CS_YOLU).read_text(encoding="utf-8")
    ts_girdileri = re.findall(r'^  "([^"]+)",$', ts, flags=re.MULTILINE)
    cs_girdileri = re.findall(r'^ {8}"([^"]+)",$', cs, flags=re.MULTILINE)
    assert tuple(ts_girdileri) == BASLANGIC_LISTESI
    assert tuple(cs_girdileri) == BASLANGIC_LISTESI
    ozet = ic_kesme.oku(kok).sha256
    assert f"SHA-256: {ozet}" in ts
    assert f"SHA-256: {ozet}" in cs


def test_iki_kez_calistirmak_ayni_bayti_verir(tmp_path: Path) -> None:
    liste_kur(tmp_path)
    assert calistir(tmp_path).exit_code == 0
    once = uretilenler(tmp_path)
    ikinci = calistir(tmp_path)
    assert ikinci.exit_code == 0
    assert "degisiklik yok" in ikinci.output
    assert "yazildi" not in ikinci.output
    assert uretilenler(tmp_path) == once


def test_liste_degisince_yalniz_gerekenler_yeniden_yazilir(tmp_path: Path) -> None:
    liste_kur(tmp_path)
    assert calistir(tmp_path).exit_code == 0
    once = uretilenler(tmp_path)
    liste_kur(tmp_path, ("a'b", "c'de", "fg'h'i", "zz'z"))
    assert calistir(tmp_path, "--check").exit_code == 1
    assert calistir(tmp_path).exit_code == 0
    sonra = uretilenler(tmp_path)
    assert sonra != once
    assert b'"zz\'z",' in sonra[ic_kesme.TS_YOLU]
    assert b'"zz\'z",' in sonra[ic_kesme.CS_YOLU]


# --- --check -----------------------------------------------------------------------------


def test_check_farki_bir_ile_cikar_ve_yazmaz(tmp_path: Path) -> None:
    liste_kur(tmp_path)
    assert calistir(tmp_path).exit_code == 0
    ts = tmp_path / ic_kesme.TS_YOLU
    bozuk = ts.read_bytes().replace(b'"c\'de"', b'"c\'dx"')
    ts.write_bytes(bozuk)
    denetim = calistir(tmp_path, "--check")
    assert denetim.exit_code == 1
    assert f"fark: {ic_kesme.TS_YOLU}" in denetim.output
    assert ic_kesme.CS_YOLU not in denetim.output
    assert ts.read_bytes() == bozuk  # --check diske yazmaz


def test_check_eksik_kopya_bir_ile_cikar(tmp_path: Path) -> None:
    liste_kur(tmp_path)
    denetim = calistir(tmp_path, "--check")
    assert denetim.exit_code == 1
    for yol in URETILEN_YOLLAR:
        assert f"fark: {yol}" in denetim.output
        assert not (tmp_path / yol).exists()


def test_check_bom_ve_crlf_kopya_farki_sayilir(tmp_path: Path) -> None:
    liste_kur(tmp_path)
    assert calistir(tmp_path).exit_code == 0
    cs = tmp_path / ic_kesme.CS_YOLU
    cs.write_bytes(b"\xef\xbb\xbf" + cs.read_bytes())
    assert calistir(tmp_path, "--check").exit_code == 1
    assert calistir(tmp_path).exit_code == 0
    cs.write_bytes(cs.read_bytes().replace(b"\n", b"\r\n"))
    assert calistir(tmp_path, "--check").exit_code == 1
    assert calistir(tmp_path).exit_code == 0
    assert calistir(tmp_path, "--check").exit_code == 0



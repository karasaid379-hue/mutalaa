def test_kati_okuma_hatalari_iki(tmp_path: Path, icerik: bytes, ileti: str) -> None:
    liste_yaz(tmp_path, icerik)
    for ek in ([], ["--check"]):
        sonuc = calistir(tmp_path, *ek)
        assert sonuc.exit_code == 2, sonuc.output
        assert ileti in sonuc.output
    assert not (tmp_path / ic_kesme.TS_YOLU).exists()
    assert not (tmp_path / ic_kesme.CS_YOLU).exists()


def test_hata_iletisi_girdi_metnini_tasimaz(tmp_path: Path) -> None:
    liste_yaz(tmp_path, b"a'b\ngizli-metin\n")
    sonuc = calistir(tmp_path)
    assert sonuc.exit_code == 2
    assert "gizli-metin" not in sonuc.output
    assert ":2:" in sonuc.output


def test_unicode_satir_ayiricilari_satir_sonu_sayilmaz(tmp_path: Path) -> None:
    # U+2028 ve U+0085 satir sonu degildir: tek (desene uymayan) girdi olarak 1. satirda reddedilir.
    liste_yaz(tmp_path, f"a'b{chr(0x2028)}c'd\n".encode())
    sonuc = calistir(tmp_path)
    assert sonuc.exit_code == 2
    assert ":1: girdi" in sonuc.output
    liste_yaz(tmp_path, "a'b\x85c'd\n".encode())
    assert ":1: girdi" in calistir(tmp_path).output


def test_dosya_yoksa_iki(tmp_path: Path) -> None:
    for ek in ([], ["--check"]):
        sonuc = calistir(tmp_path, *ek)
        assert sonuc.exit_code == 2
        assert ic_kesme.TXT_YOLU in sonuc.output


def test_kok_klasor_degilse_iki(tmp_path: Path) -> None:
    sonuc = calistir(tmp_path / "yok")
    assert sonuc.exit_code == 2


def test_coz_dogrudan() -> None:
    liste = ic_kesme.coz(b"a'b\nc'd'e\n")
    assert liste.girdiler == ("a'b", "c'd'e")
    assert liste.sha256 == hashlib.sha256(b"a'b\nc'd'e\n").hexdigest()
    with pytest.raises(GirdiHatasi, match=":2: girdi"):
        ic_kesme.coz(b"a'b\nab\n")


def test_ascii_disi_rakam_ve_harf_desene_girmez() -> None:
    # [a-z] ve [0-9] ASCII'dir; \d ve \w gibi Unicode sinifi kullanilmaz.
    for girdi in (
        f"a'{chr(0x0663)}",  # Arapca-Hint rakam uc
        f"{chr(0x0661)}a'b",  # Arapca-Hint rakam bir
        f"a'{chr(0x0131)}",  # noktasiz i
        f"{chr(0x0130)}'a",  # noktali buyuk I
    ):
        with pytest.raises(GirdiHatasi):
            ic_kesme.coz((girdi + "\n").encode("utf-8"))


def test_kaynak_yerel_ayardan_bagimsiz_ve_utf8() -> None:
    kaynak = Path(ic_kesme.__file__).read_text(encoding="utf-8")
    assert "\\d" not in kaynak
    assert ".lower(" not in kaynak
    assert ".upper(" not in kaynak
    assert "splitlines" not in kaynak.replace("str.splitlines kullanilmaz", "")
    assert "open(" not in kaynak

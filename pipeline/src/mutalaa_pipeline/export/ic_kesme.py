"""Ic kesme listesi: TypeScript ve C# kopyalari (A05.2, K-36 madde 3).

Liste arama normallestiricisinin parcasidir (K-36 madde 7). Python normallestiricisi dosyayi
dogrudan okur; TypeScript ve C# kopyalari bu modulle uretilir. Dosya kati okunur: BOM, CR,
bos satir, yinelenen, siralanmamis ya da desene uymayan girdi komutu 2 ile durdurur. Hata
iletileri satir numarasi tasir, girdi metnini tasimaz.
"""

import hashlib
import re
from pathlib import Path
from typing import Final, NamedTuple

from mutalaa_pipeline.export.ortak import GirdiHatasi, ayni_mi, yaz

TXT_YOLU: Final = "shared/data/ic-kesme.txt"
TS_YOLU: Final = "packages/search/src/generated/ic-kesme.ts"
CS_YOLU: Final = "server/Mutalaa.Domain/Text/IcKesme.g.cs"

UYARI: Final = "Bu dosya `uv run mutalaa export ic-kesme` ile üretilir; elle düzenlenmez."
# ruff RUF001-RUF003 dotless i ve dotted capital I'yi belirsiz sayar; metinde ikisi de yoktur.
ACIKLAMA: Final = (
    "Sözcük içi kesme girdileri (K-36 madde 3): küçük harfli, ASCII düzeninde, benzersiz."
)

# K-36 madde 3: `^[a-z]+('[a-z]+)+$`; fullmatch kullanilir ($ sondaki satir sonunu da eslerdi).
_GIRDI: Final = re.compile(r"[a-z]+('[a-z]+)+")
_BOM_BAYTLARI: Final = b"\xef\xbb\xbf"


class IcKesmeListesi(NamedTuple):
    """Dogrulanmis liste ve dosyanin bayt ozeti."""

    sha256: str
    girdiler: tuple[str, ...]


def coz(veri: bytes) -> IcKesmeListesi:
    """Dosya baytlarini kati UTF-8 ve K-36 madde 3 kurallariyla ayristirir."""
    if veri.startswith(_BOM_BAYTLARI):
        raise GirdiHatasi(f"{TXT_YOLU}: BOM var")
    try:
        metin = veri.decode("utf-8")
    except UnicodeDecodeError as hata:
        raise GirdiHatasi(f"{TXT_YOLU}: UTF-8 degil (bayt {hata.start})") from hata
    # str.splitlines kullanilmaz: U+2028, U+0085 gibi karakterleri de satir sonu sayar.
    satirlar = metin.split("\n")
    for no, satir in enumerate(satirlar, start=1):
        if "\r" in satir:
            raise GirdiHatasi(f"{TXT_YOLU}:{no}: CR satir sonu var; yalniz LF kullanilir")
    if satirlar[-1] != "":
        raise GirdiHatasi(f"{TXT_YOLU}: son satirdan sonra satir sonu yok")
    satirlar.pop()  # bos son parca: dosya sonundaki satir sonu
    if not satirlar:
        raise GirdiHatasi(f"{TXT_YOLU}: liste bos")
    girdiler: list[str] = []
    for no, satir in enumerate(satirlar, start=1):
        if satir == "":
            raise GirdiHatasi(f"{TXT_YOLU}:{no}: bos satir")
        if _GIRDI.fullmatch(satir) is None:
            raise GirdiHatasi(f"{TXT_YOLU}:{no}: girdi [a-z]+('[a-z]+)+ desenine uymuyor")
        if girdiler:
            onceki = girdiler[-1]
            if satir in girdiler:
                raise GirdiHatasi(f"{TXT_YOLU}:{no}: yinelenen girdi")
            if satir < onceki:  # ASCII girdilerde kod noktasi sirasi = ASCII sirasi
                raise GirdiHatasi(f"{TXT_YOLU}:{no}: girdi ASCII sirasinda degil")
        girdiler.append(satir)
    return IcKesmeListesi(hashlib.sha256(veri).hexdigest(), tuple(girdiler))


def oku(kok: Path) -> IcKesmeListesi:
    """Depodaki `shared/data/ic-kesme.txt` dosyasini okur."""
    yol = kok / TXT_YOLU
    if not yol.is_file():
        raise GirdiHatasi(f"{TXT_YOLU} yok")
    return coz(yol.read_bytes())


def _baslik(liste: IcKesmeListesi) -> list[str]:
    return [
        f"// {UYARI}",
        f"// Kaynak: {TXT_YOLU}",
        f"// SHA-256: {liste.sha256}",
    ]


def ts_metni(liste: IcKesmeListesi) -> str:
    """`packages/search` icin TypeScript kopyasi (kesmeli dizgi Prettier ile cift tirnakli)."""
    satirlar = [
        *_baslik(liste),
        "",
        f"/** {ACIKLAMA} */",
        "export const IC_KESME: readonly string[] = Object.freeze([",
        *(f'  "{girdi}",' for girdi in liste.girdiler),
        "]);",
    ]
    return "\n".join(satirlar) + "\n"


def cs_metni(liste: IcKesmeListesi) -> str:
    """`Mutalaa.Domain/Text` icin C# kopyasi."""
    satirlar = [
        "// <auto-generated/>",
        *_baslik(liste),
        "",
        "namespace Mutalaa.Domain.Text;",
        "",
        "/// <summary>",
        f"/// {ACIKLAMA}",
        "/// </summary>",
        "internal static class IcKesme",
        "{",
        "    internal static IReadOnlyList<string> Entries { get; } =",
        "    [",
        *(f'        "{girdi}",' for girdi in liste.girdiler),
        "    ];",
        "}",
    ]
    return "\n".join(satirlar) + "\n"


def tum_metinler(liste: IcKesmeListesi) -> dict[str, str]:
    """Goreli yol -> beklenen metin; iki kopya."""
    return {TS_YOLU: ts_metni(liste), CS_YOLU: cs_metni(liste)}


def uret(kok: Path) -> list[str]:
    """Listeden iki kopyayi yazar; degisen dosyalarin goreli yollarini dondurur."""
    liste = oku(kok)
    return [yol for yol, metin in tum_metinler(liste).items() if yaz(kok, yol, metin)]


def denetle(kok: Path) -> list[str]:
    """Listeden beklenen metinleri bellekte uretir; diskten farkli dosyalari dondurur."""
    liste = oku(kok)
    return [yol for yol, metin in tum_metinler(liste).items() if not ayni_mi(kok, yol, metin)]
